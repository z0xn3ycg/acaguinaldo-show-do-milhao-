-- Execute no SQL Editor do Supabase.
-- O script cria a estrutura e a visão pública somente com os campos do ranking.

create extension if not exists pgcrypto;

create table if not exists public.jogos (
  id text primary key,
  nome text not null
);

create table if not exists public.perguntas (
  id bigint generated by default as identity primary key,
  enunciado text not null unique,
  alternativa_a text not null,
  alternativa_b text not null,
  alternativa_c text not null,
  alternativa_d text not null,
  correta char(1) not null check (lower(correta) in ('a','b','c','d')),
  dificuldade text not null check (dificuldade in ('facil','media','dificil')),
  fonte text
);

alter table public.perguntas
  add column if not exists fonte text;

create table if not exists public.partidas (
  id uuid primary key,
  jogo_id text not null references public.jogos(id),
  apelido text not null check (length(trim(apelido)) > 0),
  valor_ganho numeric(12,2) not null default 0 check (valor_ganho >= 0),
  tempo_segundos numeric(12,2) not null default 0 check (tempo_segundos >= 0),
  acertos integer not null default 0 check (acertos between 0 and 9),
  motivo_encerramento text not null,
  data_hora timestamptz not null default now()
);

insert into public.jogos (id, nome)
values ('show-do-milhao', 'Show do Milhão')
on conflict (id) do nothing;

-- Melhor partida de cada apelido por jogo:
-- maior prêmio, menor tempo, data mais antiga e, por fim, ID.
-- Remove a versão anterior porque esta visão tem uma lista de colunas revisada.
drop view if exists public.ranking;
create view public.ranking as
select id, jogo_id, apelido, valor_ganho, tempo_segundos, data_hora
from (
  select p.*,
         row_number() over (
           partition by jogo_id, lower(trim(apelido))
           order by valor_ganho desc, tempo_segundos asc, data_hora asc, id asc
         ) as posicao_apelido
  from public.partidas p
) melhores
where posicao_apelido = 1;

alter table public.jogos enable row level security;
alter table public.perguntas enable row level security;
alter table public.partidas enable row level security;

drop policy if exists "leitura de jogos" on public.jogos;
create policy "leitura de jogos" on public.jogos
for select using (true);

drop policy if exists "leitura de perguntas" on public.perguntas;
create policy "leitura de perguntas" on public.perguntas
for select using (true);

drop policy if exists "inserir partidas" on public.partidas;
create policy "inserir partidas" on public.partidas
for insert with check (
  length(trim(apelido)) > 0
  and valor_ganho >= 0
  and tempo_segundos >= 0
  and acertos between 0 and 9
);

grant select on public.jogos, public.perguntas, public.ranking to anon, authenticated;
grant insert on public.partidas to anon, authenticated;

